const DICTIONARIES: Record<Language, Dictionary> = { en, sv };

let current: Language = "en";

/** BCP 47 locale for Intl formatting in the current language. */
export const getLocale = () => (current === "sv" ? "sv-SE" : "en-US");

type Ctx = { lang: Language; t: Dictionary; hostSlug: string; setLanguage: (lang: Language) => void };
const I18nContext = createContext<Ctx>({ lang: "en", t: en, hostSlug: "", setLanguage: () => {} });

/** Loads the language chosen under Settings; it applies to everyone who visits the app. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Language>(current);
  const [hostSlug, setHostSlug] = useState("");
  const [ready, setReady] = useState(false);

  const setLanguage = useCallback((next: Language) => {
    current = next;
    document.documentElement.lang = next;
    setLang(next);
  }, []);

  useEffect(() => {
    fetch("/api/locale")
      .then((r) => r.json())
      .then((d: { language?: Language; hostSlug?: string }) => {
        if (d.language === "sv" || d.language === "en") setLanguage(d.language);
        setHostSlug(d.hostSlug ?? "");
      })
      .catch(() => {})
      .finally(() => setReady(true));
  }, [setLanguage]);

  if (!ready) return null;
  return <I18nContext.Provider value={{ lang, t: DICTIONARIES[lang], hostSlug, setLanguage }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

/** Display name for an event location; online meetings take the connected provider's name. */
export function locationLabel(t: Dictionary, kind: keyof Dictionary["location"], meetingProvider?: string) {
  if (kind === "online_meeting" && meetingProvider) return meetingProvider === "microsoft" ? "Microsoft Teams" : "Google Meet";
  return t.location[kind];
}
